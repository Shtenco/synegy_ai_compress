MIB = 1048576
HERE = Path(__file__).resolve().parent
WORLD = ([f"zlib-{i}" for i in (1,3,6,9)]
         + [f"gzip-{i}" for i in (1,6,9)]
         + [f"bzip2-{i}" for i in (1,3,6,9)]
         + [f"xz-LZMA2-{i}" for i in range(10)]
         + [f"zstd-{i}" for i in (1,3,5,9,12,15,19)]
         + [f"brotli-{i}" for i in (0,3,5,7,9,11)]
         + [f"lz4-{i}" for i in (0,3,9,12)]
         + ["blosc2-LZ4", "blosc2-ZSTD"])
assert len(WORLD) == 40
RAW_FIELDS = ("index","group","name","dataset","status","original_bytes",
              "archive_bytes","encode_s","decode_s","input_sha256",
              "archive_sha256","error")
SUMMARY_FIELDS = ("no","group","name","pass","total","status",
                  "ratio_x","encode_MiB_s","decode_MiB_s",
                  "SAEI_storage_geom_pct","bytes_saved_pct","DC_payload_saving_K",
                  "TiB_saved_per_PiB","SAEI_V10",
                  "original_bytes","archive_bytes","encode_s","decode_s")

def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def atomic_text(path: Path, content: str):
    path.parent.mkdir(parents=True,exist_ok=True)
    tmp = path.with_name(path.name+".tmp")
    tmp.write_text(content,encoding="utf-8")
    os.replace(tmp,path)

def csv_save(path: Path, rows: list[dict], fields):
    buff=io.StringIO()
    w=csv.DictWriter(buff,fieldnames=fields,extrasaction="ignore")
    w.writeheader()
    w.writerows(rows)
    atomic_text(path,buff.getvalue())

def native_registry(source: Path):
    source=(source/"compression_lab").resolve()
    if not (source/"benchmark_all_81_unified_timing.py").exists():
        raise FileNotFoundError("81-system historical source not present: "+str(source))
    sys.path.insert(0,str(source))
    from benchmark_all_81_unified_timing import build_systems
    systems=build_systems()
    if len(systems)!=81 or len({s.name for s in systems})!=81:
        raise ValueError(f"Expected exactly 81 unique engines, got {len(systems)}")
    return systems

def corpus_create(path: Path):
    from benchmark_80plus_20261020 import build_corpus
    corp=build_corpus(size=5*MIB)
    if len(corp)!=11 or any(len(b)!=5*MIB for b in corp.values()):
        raise AssertionError("Expected 11 datasets, exactly 5MiB each")
    path.mkdir(parents=True,exist_ok=True)
    entries=[]
    for no,(name,contents) in enumerate(corp.items(),1):
        f=path/f"{no:02d}_{name}.bin"
        expected=digest(contents)
        if f.exists():
            if f.stat().st_size!=len(contents) or digest(f.read_bytes())!=expected:
                raise RuntimeError(f"Existing input corrupt or not same seed: {f}")
        else:
            f.write_bytes(contents)
        entries.append(dict(name=f.name,bytes=len(contents),sha256=expected))
    atomic_text(path/"manifest.json",json.dumps({
      "protocol":"LONG-121-20261024-NEW-CORPUS",
      "warning":"NOT the previous DC11x5MiB benchmark corpus; do not merge scores",
      "source":"compression_lab/benchmark_80plus_20261020.py build_corpus(5MiB)",
      "seed":20260730, "total_bytes":sum(x["bytes"] for x in entries),
      "files":entries},indent=2))
    return [path/x["name"] for x in entries]

def world_pair(name: str):
    if name.startswith("zlib-"):
        lvl=int(name.split("-")[-1])
        return lambda b:zlib.compress(b,lvl),zlib.decompress
    if name.startswith("gzip-"):
        lvl=int(name.split("-")[-1])
        return lambda b:gzip.compress(b,compresslevel=lvl,mtime=0),gzip.decompress
    if name.startswith("bzip2-"):
        lvl=int(name.split("-")[-1])
        return lambda b:bz2.compress(b,compresslevel=lvl),bz2.decompress
    if name.startswith("xz-LZMA2-"):
        lvl=int(name.split("-")[-1])
        return lambda b:lzma.compress(b,format=lzma.FORMAT_XZ,preset=lvl),lzma.decompress
    if name.startswith("zstd-"):
        import zstandard as zstd
        lvl=int(name.split("-")[-1])
        return lambda b:zstd.ZstdCompressor(level=lvl).compress(b),zstd.ZstdDecompressor().decompress
    if name.startswith("brotli-"):
        import brotli
        lvl=int(name.split("-")[-1])
        return lambda b:brotli.compress(b,quality=lvl),brotli.decompress
    if name.startswith("lz4-"):
        import lz4.frame as lz4frame
        lvl=int(name.split("-")[-1])
        return lambda b:lz4frame.compress(b,compression_level=lvl),lz4frame.decompress
    if name.startswith("blosc2-"):
        import blosc2
        codec=blosc2.Codec.LZ4 if name.endswith("LZ4") else blosc2.Codec.ZSTD
        return lambda b:blosc2.compress(b,typesize=1,clevel=5,codec=codec),blosc2.decompress
    raise ValueError("Unknown world codec: "+name)

def test_child(index: int, source: Path, corpus: Path):
    if index<81:
        spec=native_registry(source)[index]
        name,grp=spec.name,"SYNERGY"
        encode,decode=spec.engine.compress,spec.engine.decompress
    else:
        name,grp=WORLD[index-81],"WORLD"
        encode,decode=world_pair(name)
    for f in sorted(corpus.glob("*.bin")):
        original=f.read_bytes()
        out=dict(index=index+1,group=grp,name=name,dataset=f.name,
                 original_bytes=len(original),input_sha256=digest(original),
                 status="FAIL",error="")
        try:
            start=time.perf_counter()
            packed=encode(original)
            t_encode=time.perf_counter()-start
            start=time.perf_counter()
            restored=decode(packed)
            t_decode=time.perf_counter()-start
            if restored!=original or digest(restored)!=out["input_sha256"]:
                raise ValueError("Lossless restore / SHA256 mismatch")
            out.update(status="PASS", archive_bytes=len(packed),
                       archive_sha256=digest(packed),
                       encode_s=f"{t_encode:.9f}",decode_s=f"{t_decode:.9f}")
        except Exception as e:
            out["error"]=f"{type(e).__name__}: {str(e)[:600]}"
        print(json.dumps(out,ensure_ascii=False),flush=True)

def parent_worker(index,name,group,source,files,output,timeout):
    command=[sys.executable,"-u",str(Path(__file__).resolve()),
             "--source",str(source),"--output",str(output),
             "--child",str(index)]
    proc=subprocess.Popen(command,stdout=subprocess.PIPE,stderr=subprocess.PIPE,
                          text=True,start_new_session=True,
                          env={**os.environ,"PYTHONHASHSEED":"0"})
    timed_out=False
    try:
        stdout,stderr=proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out=True
        try:
            os.killpg(proc.pid,signal.SIGKILL)
        except ProcessLookupError:
            pass
        stdout,stderr=proc.communicate()
    parsed={}
    filenames={p.name for p in files}
    for line in stdout.splitlines():
        try:
            obj=json.loads(line)
        except json.JSONDecodeError:
            continue
        if obj.get("dataset") in filenames:
            parsed[obj["dataset"]]=obj
    records=[]
    for f in files:
        if f.name in parsed:
            records.append(parsed[f.name])
        else:
            records.append(dict(index=index+1,group=group,name=name,
                      dataset=f.name, status="TIMEOUT" if timed_out else "CRASH",
                      original_bytes=f.stat().st_size,input_sha256=digest(f.read_bytes()),
                      error=(f"Profile timeout {timeout}s" if timed_out else
                             f"Process exited {proc.returncode}: {stderr[-400:]}")))
    return records

def run(source: Path,output: Path,shard:int,shards:int,
        native_timeout:int,world_timeout:int):
    if shards<1 or not 0<=shard<shards:
        raise ValueError("Invalid shard index/count")
    systems=native_registry(source)
    names=[("SYNERGY",s.name) for s in systems]+[("WORLD",s) for s in WORLD]
    files=corpus_create(output/"corpus")
    rows=[]
    for n in range(shard,121,shards):
        grp,name=names[n]
        deadline=native_timeout if n<81 else world_timeout
        print(f"START {n+1}/121 {grp}: {name} (timeout {deadline}s)",flush=True)
        obs=parent_worker(n,name,grp,source,files,output,deadline)
        rows.extend(obs)
        csv_save(output/f"shard_{shard:02d}.csv",rows,RAW_FIELDS)
        atomic_text(output/f"shard_{shard:02d}_progress.json",
                    json.dumps(dict(shard=shard,shards=shards,
                       completed_profiles=len(rows)//11,
                       last_profile=n+1,last_full_pass=sum(x["status"]=="PASS" for x in obs)==11,
                       last_passed_cases=sum(x["status"]=="PASS" for x in obs),
                       git_sha=os.getenv("GITHUB_SHA"),
                       native_source_sha=os.getenv("NATIVE_SOURCE_SHA"),
                       python=platform.python_version(),
                       machine=platform.platform()),indent=2))
        print(f"SAVED {n+1}/121 {sum(x['status']=='PASS' for x in obs)}/11",flush=True)

def merge(folder:Path, output:Path):
    seen={}
    for f in sorted(folder.rglob("shard_??.csv")):
        with f.open(encoding="utf-8",newline="") as stream:
            for r in csv.DictReader(stream):
                key=(int(r["index"]),r["dataset"])
                if key in seen:
                    raise AssertionError("Duplicate case: "+str(key))
                seen[key]=r
    all_rows=sorted(seen.values(),key=lambda r:(int(r["index"]),r["dataset"]))
    output.mkdir(parents=True,exist_ok=True)
    csv_save(output/"RAW_121_ALL.csv",all_rows,RAW_FIELDS)
    table=[]
    for i in range(1,122):
        rows=[r for r in all_rows if int(r["index"])==i]
        passed=[r for r in rows if r["status"]=="PASS"]
        full=(len(rows)==11 and len(passed)==11 and
              len({r["dataset"] for r in passed})==11)
        label=rows[0]["name"] if rows else "NOT_EXECUTED"
        group="SYNERGY" if i<=81 else "WORLD"
        result=dict(no=i,group=group,name=f"{group} — {label}",
                    **{"pass":len(passed)},total=11,
                    status="PASS_11/11" if full else f"PARTIAL_{len(passed)}/11" if rows else "NOT_RUN")
        if full:
            original=sum(int(r["original_bytes"]) for r in passed)
            archive=sum(int(r["archive_bytes"]) for r in passed)
            t_enc=sum(float(r["encode_s"]) for r in passed)
            t_dec=sum(float(r["decode_s"]) for r in passed)
            ratios=[int(r["original_bytes"])/int(r["archive_bytes"]) for r in passed]
            geom=math.exp(sum(math.log(x) for x in ratios)/len(ratios))
            saved=1-archive/original
            result.update(ratio_x=f"{original/archive:.6f}",
                 encode_MiB_s=f"{original/MIB/t_enc:.6f}",
                 decode_MiB_s=f"{original/MIB/t_dec:.6f}",
                 SAEI_storage_geom_pct=f"{100*(1-1/geom):.6f}",
                 bytes_saved_pct=f"{100*saved:.6f}",
                 DC_payload_saving_K=f"{saved:.8f}",
                 TiB_saved_per_PiB=f"{1024*saved:.6f}",
                 SAEI_V10=f"{original/(archive+10*MIB*(t_enc+t_dec)):.6f}",
                 original_bytes=original,archive_bytes=archive,
                 encode_s=f"{t_enc:.6f}",decode_s=f"{t_dec:.6f}")
        table.append(result)
    csv_save(output/"ONE_TABLE_121.csv",table,SUMMARY_FIELDS)
    summary=dict(total_profiles=121,registered_synergy=81,registered_world=40,
                 measured_cases=len(all_rows),
                 expected_cases=121*11,
                 full_pass_synergy=sum(x["status"]=="PASS_11/11" for x in table[:81]),
                 full_pass_world=sum(x["status"]=="PASS_11/11" for x in table[81:]),
                 full_benchmark_complete=len(all_rows)==121*11 and
                         all(x["status"]=="PASS_11/11" for x in table),
                 note="NEW corpus, do not combine with historical results. Non-passing profiles have no full-corpus metrics.")
    atomic_text(output/"SUMMARY.json",json.dumps(summary,ensure_ascii=False,indent=2))
    print(json.dumps(summary,ensure_ascii=False,indent=2),flush=True)

def main():
    a=argparse.ArgumentParser()
    a.add_argument("--source",type=Path,default=Path("source81"))
    a.add_argument("--output",type=Path,default=Path("output_long_121"))
    a.add_argument("--shard",type=int,default=0)
    a.add_argument("--shards",type=int,default=11)
    a.add_argument("--timeout-synergy",type=int,default=480)
    a.add_argument("--timeout-world",type=int,default=540)
    a.add_argument("--child",type=int)
    a.add_argument("--merge",type=Path)
    x=a.parse_args()
    if x.merge is not None:
        merge(x.merge,x.output)
    elif x.child is not None:
        test_child(x.child,x.source,x.output/"corpus")
    else:
        run(x.source,x.output,x.shard,x.shards,
            x.timeout_synergy,x.timeout_world)

if __name__=="__main__":
    main()
