"""One reproducible, sharded 81 SYNERGY + WORLD40 5-MiB benchmark.

IMPORTANT: fresh synthetic corpus generated by benchmark_80plus_20261020.py;
NOT the older SHTENCO_DC_11x5MiB_CORPUS_20261024.zip. Never join
cross-corpus measurements or call incomplete profiles fully measured.
"""
